import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { PrismaClient } from '@prisma/client';
import { createOwnerSession, requireIsolatedServer } from './helpers/owner-session.mjs';
import { prisma as workerDb } from '../lib/prisma.ts';
import { tick } from '../lib/company/worker.ts';
const base = 'http://localhost:3063';
requireIsolatedServer(base);
const db = new PrismaClient();
let owner, browser;
try {
  assert.equal((await fetch(base + '/api/hq/company')).status, 401);
  assert.equal((await fetch(base + '/api/company/keys')).status, 401);
  assert.equal((await fetch(base + '/api/v1/tasks/missing')).status, 401);
  const catalog = await (await fetch(base + '/api/v1/capabilities')).json();
  assert(JSON.stringify(catalog).includes('animate.create_video'));
  owner = await createOwnerSession(db, base);
  const request = (path, data, origin=base) => fetch(base + path, { method: data ? 'POST' : 'GET', headers: { cookie: owner.cookie, origin, 'content-type':'application/json' }, ...(data ? { body:JSON.stringify(data) } : {}) });
  assert.equal((await request('/api/hq/company')).status, 200);
  assert.equal((await request('/api/company/keys',{ name:'browser', scopes:['tasks:read','tasks:write','knowledge:read'],monthlyLimitCents:0 },'https://attacker.invalid')).status, 403);
  const minted = await request('/api/company/keys',{ name:'browser', scopes:['tasks:read','tasks:write','knowledge:read'],monthlyLimitCents:0 });
  assert.equal(minted.status, 200); const credentials = await minted.json(); assert(credentials.key);
  const api = (path, data, extra={}) => fetch(base + path, { method:data?'POST':'GET', headers:{authorization:`Bearer ${credentials.key}`,'content-type':'application/json',...extra},...(data?{body:JSON.stringify(data)}:{}) });
  assert.equal((await api('/api/v1/status')).status,401,'Company key rejected by legacy API');
  assert(!JSON.stringify(await (await request('/api/company/keys')).json()).includes(credentials.key),'Plaintext key never returned again');
  const initialized = await api('/api/v1/agent-mcp',{jsonrpc:'2.0',id:1,method:'initialize',params:{protocolVersion:'2025-11-25',capabilities:{},clientInfo:{name:'company-browser',version:'1'}}},{accept:'application/json, text/event-stream'});
  assert.equal(initialized.status,200); assert.equal((await initialized.json()).result.serverInfo.name,'Tolley Company');
  await db.companyControl.update({ where:{id:'company'},data:{admission:true} });
  const quoted = await api('/api/v1/quotes',{capabilityId:'animate.help',input:{}}); assert.equal(quoted.status,201); const quote=await quoted.json();
  const created = await api('/api/v1/tasks',{quoteId:quote.id,maxCents:0},{'Idempotency-Key':'browser-'+Date.now()}); assert.equal(created.status,202); const task=await created.json();
  await tick(); const result = await (await api(task.pollUrl)).json(); assert.equal(result.status,'completed');
  browser=await chromium.launch({headless:true});
  const context=await browser.newContext({viewport:{width:390,height:844}});
  await context.addCookies(owner.cookie.split('; ').map(pair=>{const i=pair.indexOf('=');return {name:pair.slice(0,i),value:pair.slice(i+1),url:base};}));
  await context.route('**/*',route=>new URL(route.request().url()).origin===base?route.continue():route.abort());
  const page=await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/services/agent',{waitUntil:'networkidle',timeout:120000});
  await page.getByRole('button',{name:'Load my keys'}).click(); await page.getByRole('status').filter({hasText:'Select an existing key'}).waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  await page.screenshot({path:'/tmp/tolley-company-mobile.png'});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'/hq/company',{waitUntil:'networkidle'}); await page.getByRole('heading',{name:'Company operations'}).waitFor();
  await page.getByText('Research this month').waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
  await page.screenshot({path:'/tmp/tolley-company-hq.png'});
  const nojs=await browser.newContext({javaScriptEnabled:false}); const plain=await nojs.newPage();
  await plain.goto(base+'/services/agent'); assert((await plain.locator('main').innerText()).includes('animate.create_video'));
  assert.deepEqual(errors,[]);
  console.log('PASS live HTTP quote/task workflow, owner MFA, cross-origin rejection, key management, mobile/desktop rendering and public no-JS catalog');
} finally {await browser?.close();await owner?.cleanup();await db.$disconnect();await workerDb.$disconnect();}
