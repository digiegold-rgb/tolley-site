import { chromium } from 'playwright';
import assert from 'node:assert/strict';

const base = process.env.JOB_TEST_URL || 'http://127.0.0.1:3041';
if (!['localhost', '127.0.0.1'].includes(new URL(base).hostname)) throw new Error('Local test only');
const browser = await chromium.launch({ headless: true });
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, userAgent: 'Mozilla/5.0 (iPhone; CPU iPhone OS 18_0 like Mac OS X) AppleWebKit/605.1.15 Version/18.0 Mobile/15E148 Safari/604.1' });
  await context.route('**/*', route => new URL(route.request().url()).origin === new URL(base).origin ? route.continue() : route.abort());
  const page = await context.newPage();
  await page.goto(`${base}/job`, { waitUntil: 'networkidle', timeout: 120000 });
  assert.equal(await page.locator('h1').count(), 1);
  assert.match(await page.locator('h1').innerText(), /Part-Time Helper/);
  assert.ok(await page.locator('.job-photo img').evaluate(img => img.complete && img.naturalWidth > 0));
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: '/tmp/tolley-job-mobile.png', fullPage: true });
  await page.locator('.job-mobile-bar a').click();
  await page.getByLabel('Name', { exact: true }).fill('Local Applicant');
  await page.getByLabel('Phone', { exact: true }).fill('123');
  await page.getByLabel('Nearest cross streets').fill('Maple & Main');
  await page.getByLabel('Availability', { exact: true }).fill('Weekdays after 2; 30 minutes notice');
  await page.getByLabel('One line on why you').fill('Reliable & ready to help.');
  await page.getByRole('button', { name: 'Text my application' }).click();
  await page.locator('.job-error[role="alert"]').waitFor();
  assert.equal(await page.locator('#job-message').count(), 0);
  await page.getByLabel('Phone', { exact: true }).fill('(816) 555-0123');
  await page.getByRole('button', { name: 'Text my application' }).click();
  await page.locator('#job-message').waitFor();
  const message = await page.locator('#job-message').inputValue();
  for (const value of ['Local Applicant', '(816) 555-0123', 'Maple & Main', 'Weekdays after 2; 30 minutes notice', 'Reliable & ready to help.']) assert.ok(message.includes(value));
  const href = await page.getByRole('link', { name: 'Open it again' }).getAttribute('href');
  assert.ok(href.startsWith('sms:+19132833826&body='));
  assert.equal(decodeURIComponent(href.split('body=')[1]), message);
  assert.ok(await page.getByText('This page cannot confirm whether your text was sent.').isVisible());
  await page.getByLabel('Availability', { exact: true }).fill('Weekends');
  assert.equal(await page.locator('#job-message').count(), 0);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${base}/job`, { waitUntil: 'networkidle' });
  await page.screenshot({ path: '/tmp/tolley-job-desktop.png', fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.setViewportSize({ width: 320, height: 720 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  const noJs = await browser.newContext({ javaScriptEnabled: false });
  const staticPage = await noJs.newPage();
  await staticPage.goto(`${base}/job`);
  assert.ok(await staticPage.locator('noscript p').isVisible());
  assert.match(await staticPage.locator('noscript p').innerText(), /To apply, text your name.*913-283-3826/);
  assert.ok((await staticPage.locator('main').innerText()).includes('2.5+ installs'));
  console.log('PASS: mobile/desktop/320px, real photo, required fields, invalid phone, all five SMS answers, iPhone SMS URL, honest send state, edit resets preview, no-JS fallback.');
} finally { await browser.close(); }
