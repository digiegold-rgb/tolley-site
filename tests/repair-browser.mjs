import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { PrismaClient } from '@prisma/client';
const base = 'http://127.0.0.1:3028';
const db = new PrismaClient({datasources:{db:{url:'postgresql://postgres@127.0.0.1:55438/tolley_revenue_test'}}});
const browser = await chromium.launch({headless:true});
try {
 const page=await browser.newPage({viewport:{width:390,height:844}});
 await page.goto(base+'/repair?utm_source=repair-test',{waitUntil:'networkidle',timeout:120000});
 await page.getByRole('heading',{level:1}).waitFor();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
 assert.equal(await page.locator('link[rel="canonical"]').getAttribute('href'),'https://www.tolley.io/repair');
 await page.screenshot({path:'/tmp/tolley-repair-mobile.png',fullPage:true});
 await page.getByLabel('Your name',{exact:true}).fill('Repair browser fixture');
 await page.getByLabel('Property city or address').fill('Independence');
 await page.getByLabel('What’s going on?').fill('Patch drywall and remove furniture.');
 await page.getByRole('button',{name:'Send my request'}).click();
 await page.getByRole('alert').filter({hasText:'phone number or email'}).waitFor();
 await page.getByLabel('Email',{exact:true}).fill('repair-test@example.invalid');
 await page.getByLabel('Home repairs',{exact:true}).check();
 await page.getByLabel('Furniture removal',{exact:true}).check();
 await page.route('**/api/lead/action',route=>route.fulfill({status:500,json:{error:'test failure'}}));
 await page.getByRole('button',{name:'Send my request'}).click();
 await page.getByRole('alert').filter({hasText:'not saved'}).waitFor();
 assert.equal(await page.getByLabel('Your name',{exact:true}).inputValue(),'Repair browser fixture');
 await page.unroute('**/api/lead/action');
 let payload;
 page.on('request',r=>{if(r.url().endsWith('/api/lead/action'))payload=r.postDataJSON()});
 await page.getByRole('button',{name:'Send my request'}).click();
 await page.getByRole('status').filter({hasText:'Your request is saved'}).waitFor({timeout:120000});
 const lead=await db.leadAction.findFirstOrThrow({where:{subsite:'repair',email:'repair-test@example.invalid'},orderBy:{createdAt:'desc'}});
 assert.equal(lead.structured.services,'repairs, removal');
 assert.equal(lead.structured.address,'Independence');
 assert.ok(await db.hqCustomerLink.findUnique({where:{kind_sourceId:{kind:'action',sourceId:lead.id}}}), 'Saved inquiry linked to owner customer history');
 assert.equal(lead.attribution.campaignSource,'repair-test');
 const retry=await page.request.post(base+'/api/lead/action',{data:payload});
 assert.equal(retry.status(),200,await retry.text());
 assert.equal((await retry.json()).receiptToken,lead.receiptToken);
 assert.equal(await db.leadAction.count({where:{requestKey:lead.requestKey}}),1);
 assert.ok(await db.leadNotification.count({where:{leadId:lead.id}})>=2);
 const denied=await page.request.get(base+'/api/hq/customers');assert.equal(denied.status(),401);
 await page.setViewportSize({width:1440,height:1000});await page.goto(base+'/repair',{waitUntil:'networkidle'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false);
 await page.screenshot({path:'/tmp/tolley-repair-desktop.png',fullPage:true});
 console.log('PASS: responsive page, canonical, contact validation, failed-save retention, real saved inquiry, retry deduplication, notification outbox, owner access gate');
}finally{await browser.close();await db.$disconnect()}
