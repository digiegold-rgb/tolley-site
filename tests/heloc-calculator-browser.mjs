import assert from 'node:assert/strict';
import { chromium, webkit, devices } from 'playwright';
import { expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

const base = process.env.CALCULATOR_TEST_URL || 'http://127.0.0.1:3027';
const output = process.env.CALCULATOR_SCREENSHOTS || '/tmp/tolley-heloc-screenshots';
await mkdir(output, { recursive: true });
for (const [name, engine] of [['chromium', chromium], ['webkit', webkit]]) {
  if (process.env.CALCULATOR_BROWSER && process.env.CALCULATOR_BROWSER !== name) continue;
  const browser = await engine.launch({ headless: true, ...(name === 'webkit' && process.env.CALCULATOR_WEBKIT_EXECUTABLE ? { executablePath: process.env.CALCULATOR_WEBKIT_EXECUTABLE } : {}) });
  try {
    const context = await browser.newContext({ ...devices['iPhone 13'], deviceScaleFactor: 1, defaultBrowserType: undefined, colorScheme: 'light' });
    await context.route('**/*', route => new URL(route.request().url()).origin === new URL(base).origin ? route.continue() : route.abort());
    await context.addInitScript(() => Object.defineProperty(navigator, 'share', { configurable: true, value: async data => { window.__sharedEstimate = data; } }));
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    const fill = async (id, value) => { await page.locator(`#heloc-${id}`).fill(String(value)); await page.locator(`#heloc-${id}`).blur(); };
    const expand = async text => { const details = page.locator('#heloc-panel details').filter({ has: page.locator('summary').filter({ hasText: text }) }); if (!(await details.getAttribute('open') !== null)) await details.locator('summary').click(); };
    const reset = () => page.getByRole('button', { name: 'Reset calculator' }).click();
    await page.goto(`${base}/agent/calculator`, { waitUntil: 'networkidle', timeout: 180000 });
    await expect(page.locator('[data-ready]')).toHaveAttribute('data-ready', 'true');
    await expect(page.getByTestId('monthly-payment')).toHaveText('$2,740');
    await page.getByRole('tab', { name: /Mortgage/ }).focus(); await page.keyboard.press('ArrowRight');
    await expect(page.getByRole('tab', { name: /HELOC/ })).toBeFocused();
    await expect(page.getByRole('tab', { name: /HELOC/ })).toHaveAttribute('aria-selected', 'true');
    await expect(page.locator('#mortgage-panel')).toBeHidden();
    await expect(page.getByTestId('heloc-payment')).toHaveText('$333');
    await expect(page.getByTestId('heloc-repayment')).toContainText('$418');
    await expect(page.getByTestId('heloc-capacity')).toHaveText('$90,000');
    assert.equal(new URL(page.url()).searchParams.get('tab'), 'heloc');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: `${output}/${name}-heloc-mobile-light.png`, fullPage: true });
    await fill('homeValue', 500000); await expect(page.getByTestId('heloc-capacity')).toHaveText('$175,000');
    await page.locator('#heloc-draw-slider').focus(); await page.keyboard.press('ArrowRight');
    await expect(page.locator('#heloc-drawn')).toHaveValue('50,100');
    await fill('drawn', 50000);
    await page.locator('#heloc-draw-mode').selectOption('percent');
    await expect(page.getByTestId('heloc-payment')).toHaveText('$500');
    await expand('Extra payments'); await fill('extraPayment', 500);
    await expect(page.getByTestId('heloc-payment')).toHaveText('$1,000');
    await reset();
    await fill('rate', 7.125); await expect(page.locator('#heloc-rate')).toHaveValue('7.125');
    await page.getByRole('button', { name: 'Index + margin', exact: true }).click();
    await fill('indexRate', 7); await fill('margin', -1);
    await expect(page.getByTestId('heloc-payment')).toHaveText('$250');
    await expand('Rate floor'); await fill('floor', 7);
    await expect(page.getByTestId('heloc-payment')).toHaveText('$292');
    await page.getByRole('checkbox', { name: /Use an introductory rate/ }).check(); await fill('promoRate', 0);
    await expect(page.getByTestId('heloc-payment')).toHaveText('$0');
    await fill('annualFee', 120); await expect(page.getByTestId('heloc-payment')).toHaveText('$10');
    await reset();
    await expand('Fixed-rate option'); await page.getByRole('checkbox', { name: /Convert a portion/ }).check();
    await page.getByRole('button', { name: /Fix the entire/ }).click(); await fill('lockRate', 6); await fill('lockYears', 10);
    await expect(page.getByTestId('heloc-payment')).toHaveText('$555');
    await fill('existingHousing', 2000); await expect(page.getByTestId('heloc-combined')).toContainText('$2,555');
    await page.getByRole('button', { name: 'Switch light or dark appearance' }).click();
    await page.screenshot({ path: `${output}/${name}-heloc-mobile-dark.png`, fullPage: true });
    await expand('Total cost'); await expect(page.getByRole('table', { name: 'Year-by-year balance (before any final balloon)' })).toBeVisible();
    await page.getByRole('button', { name: 'Share this HELOC estimate' }).click();
    const shared = await page.evaluate(() => window.__sharedEstimate);
    assert.equal(new URL(shared.url).searchParams.get('tab'), 'heloc');
    assert.equal(JSON.parse(new URL(shared.url).searchParams.get('heloc')).lock, true);
    await page.goto(shared.url, { waitUntil: 'networkidle' });
    await expect(page.getByTestId('heloc-payment')).toHaveText('$555');
    await expect(page.getByRole('tab', { name: /HELOC/ })).toHaveAttribute('aria-selected', 'true');
    await expect(page.locator('[data-theme]')).toHaveAttribute('data-theme', 'dark');
    await page.getByRole('tab', { name: /Mortgage/ }).click();
    await expect(page.getByTestId('monthly-payment')).toHaveText('$2,740');
    await page.getByRole('tab', { name: /HELOC/ }).click();
    await expect(page.getByTestId('heloc-payment')).toHaveText('$555');
    await reset(); await expand('Extra payments'); await page.locator('#heloc-repayment-type').selectOption('balloon');
    await expect(page.getByTestId('heloc-repayment')).toContainText('$50,000');
    await fill('drawYears', 0); await expect(page.getByTestId('heloc-payment')).toHaveText('$50,000');
    await expect(page.getByText('Your remaining balance is due as a lump sum.')).toBeVisible();
    await reset(); await fill('lineLimit', 50000); await fill('openingFees', 1000); await expand('Draw fees');
    await page.getByRole('checkbox', { name: /Add setup and draw fees/ }).check();
    await expect(page.getByText(/Financed fees put this balance/)).toBeVisible();
    await fill('lineLimit', 0); await page.getByRole('checkbox', { name: /Add setup and draw fees/ }).uncheck();
    await expect(page.getByTestId('heloc-payment')).toHaveText('$0'); await expect(page.locator('#heloc-draw-slider')).toBeDisabled();
    await page.setViewportSize({ width: 320, height: 740 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${name} overflows at 320px`);
    await reset();
    await page.evaluate(() => { Object.defineProperty(navigator, 'share', { configurable: true, value: undefined }); Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('Unavailable'); } } }); });
    await page.getByRole('button', { name: 'Share this HELOC estimate' }).click();
    await expect(page.getByRole('textbox', { name: 'Shareable HELOC estimate link' })).toBeVisible();
    assert.deepEqual(errors, []);
    const desktop = await context.newPage();
    await desktop.setViewportSize({ width: 1440, height: 1000 });
    await desktop.goto(`${base}/agent/calculator?tab=heloc`, { waitUntil: 'networkidle' });
    await expect(desktop.locator('[data-ready]')).toHaveAttribute('data-ready', 'true');
    await expect(desktop.getByRole('tab', { name: /HELOC/ })).toHaveAttribute('aria-selected', 'true');
    await expect(desktop.getByTestId('heloc-payment')).toBeVisible();
    await expect(desktop.getByTestId('heloc-payment')).toHaveText('$333');
    await desktop.screenshot({ path: `${output}/${name}-heloc-desktop.png`, fullPage: true });
    console.log(`${name}: HELOC tabs, sliders, payment modes, rates, fees, fixed conversions, balloon, sharing, zero balances and mobile layouts passed`);
  } finally { await browser.close(); }
}
